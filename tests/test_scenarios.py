# 4. send/receive contradiction


class SendReceiveTests(PipelineHarness):
    def build(self) -> list[CaseBuilder]:
        h1 = CaseBuilder("h1", SEED_H1)
        h1.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        h1.event("s1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 10 * S,
                 kind="send", message_id="m1")

        h2 = CaseBuilder("h2", SEED_H2)
        h2.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        # The receiver is timestamped 5 s *before* the sender.
        h2.event("r1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 5 * S,
                 kind="recv", message_id="m1")
        return [h1, h2]

    def test_send_after_receive_is_a_contradiction(self):
        result, _ = self.run_case(self.build())
        self.assertEqual(result["status"], "contradiction")
        self.assertEqual(result["unsat_cores"][0]["size"], 3)

    def test_core_names_the_message_constraint(self):
        result, _ = self.run_case(self.build())
        core = result["unsat_cores"][0]
        kinds = sorted(m["constraint"]["kind"] for m in core["constraints"])
        self.assertEqual(kinds, ["message", "wall_hi", "wall_lo"])
        message_member = next(
            m for m in core["constraints"] if m["constraint"]["kind"] == "message"
        )
        self.assertEqual(message_member["constraint"]["events"], ["s1", "r1"])
        self.assertEqual(
            sorted(e["id"] for e in message_member["events"]),
            ["r1", "s1"],
        )

    def test_only_the_contradicted_ids_are_in_the_core(self):
        result, _ = self.run_case(self.build())
        mentions = {
            e["id"]
            for m in result["unsat_cores"][0]["constraints"]
            for e in m["events"]
        }
        self.assertEqual(mentions, {"s1", "r1"})

    def test_withdrawing_the_message_restores_order(self):
        result, _ = self.run_case(self.build())
        quarantine = result["quarantine"]
        self.assertEqual(quarantine["scope"], "ordering_only")
        self.assertEqual(quarantine["withdrawn_kinds"], ["message"])
        self.assertTrue(quarantine["feasible"])
        # Without the (impossible) message, the two 5 s/10 s windows order
        # themselves: r1 is provably before s1.
        entry = [
            p for p in quarantine["pairwise"] if {p["a"], p["b"]} == {"r1", "s1"}
        ][0]
        # The pair is listed as (a=s1, b=r1); "after" means s1 follows r1.
        self.assertEqual((entry["a"], entry["b"], entry["verdict"]), ("s1", "r1", "after"))

    def test_valid_message_between_two_hosts_is_ordered(self):
        h1 = CaseBuilder("h1", SEED_H1)
        h1.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        h1.event("s9", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 10 * S,
                 kind="send", message_id="m9")
        h2 = CaseBuilder("h2", SEED_H2)
        h2.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        h2.event("r9", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 11 * S,
                 kind="recv", message_id="m9")
        result, _ = self.run_case([h1, h2])
        self.assertEqual(result["status"], "ok")
        entry = pair(result, "s9", "r9")
        self.assertEqual(entry["verdict"], "before")
        self.assertEqual(entry["reason"], "message_causality")
        self.assertEqual(entry["bound_ns"], -1_000_000_000)


