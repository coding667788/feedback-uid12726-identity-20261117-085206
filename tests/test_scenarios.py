"""End-to-end tests for the five required acceptance scenarios.

Every test asserts a concrete verdict, window, core or hash — none of them
only "ran without raising".  All data is generated by the in-memory builder in
``_support`` with fixed keys, so every assertion is reproducible.
"""

from __future__ import annotations

import json
import os
import unittest

from _support import (
    MS,
    S,
    BASE,
    SEED_H1,
    SEED_H2,
    CaseBuilder,
    TempDirMixin,
    codes,
    pair,
    timeline_event,
)

from solution.pipeline import load_cases, run_case


class PipelineHarness(TempDirMixin):
    def run_case(self, builder_or_sources, **kwargs):
        case_dir = self.make_case_dir()
        if isinstance(builder_or_sources, CaseBuilder):
            sources = [builder_or_sources]
        else:
            sources = list(builder_or_sources)
        paths = []
        for builder in sources:
            # Unique file name per occurrence so two files from the same host
            # (a re-export) get distinct source ids.
            index = len(paths) + 1
            name = f"host_{builder.host}_{index}.jsonl"
            case_dir.write(name, builder.render())
            paths.append(name)
        cases_path = case_dir.cases(paths, **kwargs)
        return run_case(load_cases(cases_path)), case_dir


