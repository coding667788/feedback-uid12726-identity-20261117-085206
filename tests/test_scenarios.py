# 5. partially overlapping intervals


class OverlapTests(PipelineHarness):
    def build(self, *, overlap: bool) -> list[CaseBuilder]:
        h1 = CaseBuilder("h1", SEED_H1)
        h1.boot("b1", offset_lo_ms=-1500, offset_hi_ms=1500)
        h1.event("a", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 10 * S)
        h2 = CaseBuilder("h2", SEED_H2)
        h2.boot("b1", offset_lo_ms=-1500, offset_hi_ms=1500)
        h2.event("b", "b1", 1, mono_ns=1 * S,
                 wall_ns=BASE + (10 * S if overlap else 60 * S))
        return [h1, h2]

    def test_overlapping_windows_stay_concurrent(self):
        result, _ = self.run_case(self.build(overlap=True))
        self.assertTrue(result["order"]["feasible"])
        entry = pair(result, "a", "b")
        self.assertEqual(entry["verdict"], "concurrent")
        self.assertEqual(entry["reason"], "no_provable_order")
        # Both directions are representable, which is what concurrency means.
        self.assertGreater(entry["separation_bounds_ns"]["t_b_minus_t_a_upper"], 0)
        self.assertGreater(entry["separation_bounds_ns"]["t_a_minus_t_b_upper"], 0)
        # The possible intervals really do overlap.
        a = timeline_event(result, "a")["possible_interval"]
        b = timeline_event(result, "b")["possible_interval"]
        self.assertLessEqual(a["lo_ns"], b["hi_ns"])
        self.assertLessEqual(b["lo_ns"], a["hi_ns"])
        self.assertEqual(entry["a"], "a")

    def test_disjoint_windows_do_give_an_order(self):
        result, _ = self.run_case(self.build(overlap=False))
        entry = pair(result, "a", "b")
        self.assertEqual(entry["verdict"], "before")
        self.assertEqual(entry["reason"], "calibration_windows_disjoint")

    def test_topological_display_breaks_ties_deterministically(self):
        result, _ = self.run_case(self.build(overlap=True))
        topo = result["order"]["topological"]
        self.assertEqual(topo["status"], "ok")
        self.assertEqual(topo["certificate"]["concurrent_pairs"], 1)
        self.assertEqual(topo["certificate"]["concurrent_pairs_broken_by_tie_break"], 1)
        # a and b are concurrent, so the tie-break decides; it is stable.
        again, _ = self.run_case(self.build(overlap=True))
        self.assertEqual(topo["sequence"], again["order"]["topological"]["sequence"])

    def test_concurrency_is_symmetric(self):
        result, _ = self.run_case(self.build(overlap=True))
        self.assertEqual(result["order"]["concurrent"]["a"], ["b"])
        self.assertEqual(result["order"]["concurrent"]["b"], ["a"])
        self.assertEqual(result["order"]["precedes"]["a"], [])
        self.assertEqual(result["order"]["follows"]["a"], [])


