# 1. clock rollback


class ClockRollbackTests(PipelineHarness):
    def build(self) -> CaseBuilder:
        """boot b1 on one host; the wall clock jumps 30 s back at seq 3."""
        b = CaseBuilder("h1", SEED_H1)
        b.boot("b1", offset_lo_ms=-100, offset_hi_ms=100, mono_earliest_ns=0)
        b.event("r1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 1 * S)
        b.event("r2", "b1", 2, mono_ns=2 * S, wall_ns=BASE + 2 * S)
        # True instant 3 s, but the clock now reads 30 s earlier.
        b.event("r3", "b1", 3, mono_ns=3 * S, wall_ns=BASE + 3 * S - 30 * S)
        b.event("r4", "b1", 4, mono_ns=5 * S, wall_ns=BASE + 5 * S - 30 * S)
        return b

    def test_status_is_contradiction_and_a_core_is_reported(self):
        result, _ = self.run_case(self.build())
        self.assertEqual(result["status"], "contradiction")
        self.assertEqual(result["unsat_cores"][0]["size"], 3)
        self.assertIn("E_CONTRADICTION", codes(result))

    def test_core_contains_the_calibration_and_the_elapsed_time(self):
        result, _ = self.run_case(self.build())
        kinds = sorted(m["constraint"]["kind"] for m in result["unsat_cores"][0]["constraints"])
        self.assertEqual(kinds, ["mono_elapsed", "wall_hi", "wall_lo"])

    def test_core_is_minimal_by_deletion(self):
        result, _ = self.run_case(self.build())
        certificate = result["unsat_cores"][0]["certificate"]
        self.assertEqual(len(certificate), 3)
        for entry in certificate:
            self.assertTrue(entry["feasible_without"])
        self.assertTrue(result["cross_check"]["cores"][0]["minimal"])
        self.assertFalse(result["cross_check"]["cores"][0]["core_infeasible"] is False)

    def test_withdrawing_the_core_restores_a_timeline(self):
        result, _ = self.run_case(self.build())
        quarantine = result["quarantine"]
        self.assertTrue(quarantine["feasible"])
        self.assertEqual(
            quarantine["topological"]["sequence"],
            ["r1", "r2", "r3", "r4"],
        )

    def test_wall_readings_still_produce_possible_intervals(self):
        result, _ = self.run_case(self.build())
        r3 = timeline_event(result, "r3")
        # The stated wall time was BASE + 3 s - 30 s; the interval is that +- 100 ms.
        expected_lo = (BASE + 3 * S - 30 * S) - 100 * MS
        expected_hi = (BASE + 3 * S - 30 * S) + 100 * MS
        self.assertEqual(r3["possible_interval"]["lo_ns"], expected_lo)
        self.assertEqual(r3["possible_interval"]["hi_ns"], expected_hi)
        # No feasible window is claimed while the system is contradictory.
        self.assertIsNone(r3["feasible_window"])


