# 2. reboot


class RebootTests(PipelineHarness):
    def build(self) -> list[CaseBuilder]:
        b = CaseBuilder("h1", SEED_H1)
        b.boot("b1", offset_lo_ms=-100, offset_hi_ms=100, mono_earliest_ns=0)
        b.event("b1-e1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 1 * S)
        b.event("b1-e2", "b1", 2, mono_ns=2 * S, wall_ns=BASE + 2 * S,
                kind="send", message_id="m1")
        b.boot("b2", offset_lo_ms=-100, offset_hi_ms=100, mono_earliest_ns=0,
               follows=("h1", "b1"))
        # The counter restarted at 0: mono is *smaller* than on b1.
        b.event("b2-e1", "b2", 1, mono_ns=1 * S, wall_ns=BASE + 600 * S,
                kind="recv", message_id="m1")
        b.event("b2-e2", "b2", 2, mono_ns=2 * S, wall_ns=BASE + 601 * S)
        return [b]

    def test_counters_are_not_compared_across_boots(self):
        result, _ = self.run_case(self.build())
        # No diagnostic may claim a monotonic anomaly: b2's counter restarting
        # is normal and must not be compared against b1's readings.
        self.assertNotIn("E_MONO_ANOMALY", codes(result))
        self.assertNotIn("E_SEQ_DUP", codes(result))

    def test_reboot_order_is_proved_via_message_and_declaration(self):
        result, _ = self.run_case(self.build())
        self.assertTrue(result["order"]["feasible"])
        entry = pair(result, "b1-e2", "b2-e1")
        # The direct evidence is the message; the solver may also use the
        # declared reboot order, so the label is one of the two.
        self.assertEqual(entry["verdict"], "before")
        self.assertIn(entry["reason"], {"message_causality", "declared_reboot_order"})
        self.assertLess(entry["bound_ns"], 0)

    def test_sequence_within_each_boot_is_respected(self):
        result, _ = self.run_case(self.build())
        self.assertEqual(pair(result, "b1-e1", "b1-e2")["verdict"], "before")
        self.assertEqual(pair(result, "b2-e1", "b2-e2")["verdict"], "before")

    def test_boot_order_certificate_lists_the_implied_edges(self):
        result, _ = self.run_case(self.build())
        topo = result["order"]["topological"]
        self.assertEqual(topo["status"], "ok")
        self.assertEqual(topo["certificate"]["edges_checked"], len(topo["edges"]))
        self.assertEqual(topo["certificate"]["edges_in_violation"], [])
        self.assertEqual(topo["sequence"][0], "b1-e1")
        self.assertEqual(topo["sequence"][-1], "b2-e2")


