# 3. duplicate collection


class DuplicateCollectionTests(PipelineHarness):
    def build(self) -> list[CaseBuilder]:
        original = CaseBuilder("h1", SEED_H1)
        original.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        original.event("e1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 1 * S)
        original.event("e2", "b1", 2, mono_ns=2 * S, wall_ns=BASE + 2 * S)

        # Second acquisition pass: same content, CRLF line endings.
        reexport = CaseBuilder("h1", SEED_H1, newline="\r\n")
        reexport.boot("b1", offset_lo_ms=0, offset_hi_ms=0)
        reexport.event("e1", "b1", 1, mono_ns=1 * S, wall_ns=BASE + 1 * S)
        reexport.event("e2", "b1", 2, mono_ns=2 * S, wall_ns=BASE + 2 * S)
        return [original, reexport]

    def test_identical_records_merge_into_one_node(self):
        result, _ = self.run_case(self.build())
        self.assertEqual(len(result["timeline"]), 2)
        e1 = timeline_event(result, "e1")
        self.assertEqual(len(e1["occurrences"]), 2)
        self.assertEqual(sorted(o["source"] for o in e1["occurrences"]), ["host_h1_1", "host_h1_2"])
        # Both occurrences still carry their own byte range.
        self.assertEqual(len({o["byte_start"] for o in e1["occurrences"]}), 2)

    def test_duplicates_are_reported_as_evidence_not_errors(self):
        result, _ = self.run_case(self.build())
        duplicate_codes = [d for d in result["diagnostics"] if d["code"] == "E_DUPLICATE"]
        self.assertEqual(len(duplicate_codes), 3)  # boot + two events
        for diag in duplicate_codes:
            self.assertIn("byte_start", diag)
            self.assertIn("byte_end", diag)
            self.assertIn("line", diag)
        self.assertEqual(result["status"], "ok")
        self.assertEqual(result["conflicts"], [])

    def test_same_id_with_different_content_is_a_conflict(self):
        case_dir = self.make_case_dir()
        original = self.build()[0]
        case_dir.write("a.jsonl", original.render())
        # Re-sign the same id with a different seq: legitimate signature,
        # different content.
        from _support import sign_record

        lines = original.render().decode("utf-8").splitlines()
        changed = json.loads(lines[3])
        changed["seq"] = 9
        lines[3] = json.dumps(sign_record(changed, SEED_H1))
        case_dir.write("b.jsonl", ("\n".join(lines) + "\n").encode("utf-8"))
        cases = case_dir.cases(["a.jsonl", "b.jsonl"])
        result = run_case(load_cases(cases))

        self.assertEqual(result["status"], "conflict")
        self.assertEqual(len(result["conflicts"]), 1)
        self.assertEqual(result["conflicts"][0]["id"], "e2")
        self.assertEqual(result["conflicts"][0]["variant_count"], 2)
        self.assertEqual(
            result["models"]["excluded_events"],
            [{"id": "e2", "reason": "E_ID_CONFLICT"}],
        )
        self.assertEqual([e["id"] for e in result["timeline"]], ["e1"])


